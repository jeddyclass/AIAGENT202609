import numpy as np

nodes = ["台北車站", "中山站", "西門站"]

# 多重圖鄰接矩陣 (記錄通路數量)
# 對角線不為 0（有自環觀光巴士）；格子大於 1（有捷運+公車多條路線）
multi_matrix = np.array([
    [1, 2, 1],  # 台北車站：到自己(1條)、到中山(2條)、到西門(1條)
    [2, 0, 0],  # 中山站  ：到北車(2條)、到自己(0條)、到西門(0條)
    [1, 0, 0]   # 西門站  ：到北車(1條)、到中山(0條)、到自己(0條)
])

print("--- 複雜交通通路數量矩陣 (原表) ---")
print(multi_matrix)

# 應用：矩陣自乘 (平方)，計算「轉乘一次（走2步）」的所有路線組合
routes_2_steps = np.linalg.matrix_power(multi_matrix, 2)

print("\n--- 轉乘一次後，所有可能的路線組合數 ---")
print(routes_2_steps)

print(f"\n【電腦分析】:")
print(f"原本「中山站」到「西門站」直達是 {multi_matrix[1][2]} 條線。")
print(f"但限制轉乘一次時，中山到西門的走法高達 【{routes_2_steps[1][2]}】 種！")
print("(原因：中山去北車有 2 種交通工具，北車到西門有 1 種，2 × 1 = 2 種組合)")
