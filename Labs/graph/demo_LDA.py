import numpy as np

# 1. 定義節點：[0: 中山, 1: 北車, 2: 西門]
# 鄰接矩陣 A (無向圖)
A = np.array([
    [0, 1, 0],
    [1, 0, 1],
    [0, 1, 0]
])

# 度矩陣 D (對角線為各節點度數)
D = np.diag(np.sum(A, axis=1))

# 圖拉普拉斯矩陣 L = D - A
L = D - A

print("--- 拉普拉斯矩陣 L ---")
print(L)

# 2. 人潮向量 x: [中山 100, 北車 500, 西門 200]
x = np.array([100, 500, 200])

# 計算擴散通量 (L @ x)
diff = L @ x
print("\n--- 各站相對於鄰居的淨差距 (L @ x) ---")
print(f"中山淨差: {diff[0]} (比北車少 400)")
print(f"北車淨差: {diff[1]} (比鄰居多出 700，具外流趨勢)")
print(f"西門淨差: {diff[2]} (比北車少 300)")

# 3. 特徵分解 (展示譜圖特性)
eigenvalues, eigenvectors = np.linalg.eigh(L)

print("\n--- 特徵值 (由小到大) ---")
print(np.round(eigenvalues, 4))
print("\n--- 菲德勒向量 (第二小特徵值對應之向量，可用於社群劃分) ---")
print(np.round(eigenvectors[:, 1], 4))