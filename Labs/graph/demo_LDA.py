## ### 第三步：全圖能量與頻譜切割（為什麼 AI 與演算法這麼愛它？）
## 
## 當我們把所有節點的差距平方加總，會得到二次型（Quadratic Form）：
## 
## $$x^T L x = \sum_{(i, j) \in E} (x_i - x_j)^2$$
## 
## * **平滑度指標（Dirichlet Energy）：** 這個數值代表圖上的信號 $x$ 有多「平滑」。如果相連的節點數值都很接近，這項總和就很小；如果相連節點數值差異極大，總和就會暴增。
## * **特徵值與頻譜分群（Spectral Clustering）：**
##   * 最小特徵值一定是 $\lambda_1 = 0$，對應的全 1 向量代表整體平衡、無擴散。
##   * **第二小特徵值 $\lambda_2$（菲德勒值，Fiedler value）：** 代表這張圖有多難被切斷。其對應的特徵向量（Fiedler vector）能自動把圖切成兩大社群——只要看正負號，就能把緊密相連的節點分在同一組。
