import numpy as np

# -------------------------------------------------------------
# 1. 建立小型知識圖譜實體與關係
# -------------------------------------------------------------
# 實體清單 (共 6 個實體)
entities = [
    "愛因斯坦",       # 0: 物理學家 (已知標籤)
    "相對論",         # 1: 物理概念 (未知)
    "光電效應",       # 2: 物理/化學交叉 (未知)
    "居禮夫人",       # 3: 物理/化學家 (已知標籤)
    "放射性元素",     # 4: 化學概念 (未知)
    "週期表"          # 5: 化學概念 (未知)
]
n = len(entities)

# 鄰接矩陣 A (包含無向連線與關係權重)
# 權重可代表關聯強度 (例如關係類型權重)
A = np.zeros((n, n), dtype=float)

edges = [
    (0, 1, 1.0),  # 愛因斯坦 - 提出 -> 相對論
    (0, 2, 1.0),  # 愛因斯坦 - 解釋 -> 光電效應
    (3, 2, 0.8),  # 居禮夫人 - 相關 -> 光電效應
    (3, 4, 1.2),  # 居禮夫人 - 發現 -> 放射性元素
    (4, 5, 1.0),  # 放射性元素 - 歸入 -> 週期表
]

for i, j, w in edges:
    A[i, j] = w
    A[j, i] = w

# -------------------------------------------------------------
# 2. 計算對稱正規化拉普拉斯矩陣 (Normalized Symmetric Laplacian)
# L_sym = I - D^(-1/2) * A * D^(-1/2)
# 擴散算子 (Diffusion Operator) P = D^(-1/2) * A * D^(-1/2) = I - L_sym
# -------------------------------------------------------------
degrees = np.sum(A, axis=1)
d_inv_sqrt = np.power(degrees, -0.5)
d_inv_sqrt[np.isinf(d_inv_sqrt)] = 0.0
D_inv_sqrt = np.diag(d_inv_sqrt)

# 語意傳播轉移矩陣 S (對稱正規化)
S = D_inv_sqrt @ A @ D_inv_sqrt

# 圖拉普拉斯矩陣
L_sym = np.eye(n) - S

# -------------------------------------------------------------
# 3. 定義初始已知標籤 (Label Matrix Y)
# 分類目標：[物理領域 (Physics), 化學領域 (Chemistry)]
# -------------------------------------------------------------
Y = np.zeros((n, 2))

# 只有愛因斯坦 (0) 與 居禮夫人 (3) 有初始地面真值標籤 (Ground Truth)
Y[0] = [1.0, 0.0]  # 愛因斯坦: 100% 物理
Y[3] = [0.3, 0.7]  # 居禮夫人: 30% 物理, 70% 化學

# 記錄哪些節點是固定的錨點 (Clamped Nodes)
is_labeled = np.array([True, False, False, True, False, False])

# -------------------------------------------------------------
# 4. 利用拉普拉斯熱傳導進行迭代擴散
# 公式: F(t+1) = alpha * S * F(t) + (1 - alpha) * Y
# -------------------------------------------------------------
alpha = 0.85  # 擴散保留係數
F = Y.copy()

for step in range(30):
    # 透過拉普拉斯算子向相鄰實體擴散語意
    F = alpha * (S @ F) + (1 - alpha) * Y
    # 固定初始標籤節點的真值 (Hard Clamping)
    F[is_labeled] = Y[is_labeled]

# -------------------------------------------------------------
# 5. 輸出推論結果
# -------------------------------------------------------------
print(f"{'實體名稱':<10} | {'物理偏向 (Score)':<18} | {'化學偏向 (Score)':<18} | {'預測領域'}")
print("-" * 65)

for i, name in enumerate(entities):
    physics_score = F[i, 0]
    chem_score = F[i, 1]
    pred = "物理學" if physics_score > chem_score else "化學"
    status = " (已知標籤)" if is_labeled[i] else ""
    print(f"{name + status:<12} | {physics_score:<18.4f} | {chem_score:<18.4f} | {pred}")